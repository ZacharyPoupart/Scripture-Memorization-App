// One-off generator for src/core/versification.ts (verses per chapter, KJV numbering).
// Usage: npm i --no-save es-kjv && npm run gen:versification
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
const require = createRequire(import.meta.url);
const { verses } = require('es-kjv');

const counts = new Map();
for (const key of Object.keys(verses)) {
  const [, book, ch, v] = key.match(/^(.*) (\d+):(\d+)$/);
  if (!counts.has(book)) counts.set(book, []);
  const arr = counts.get(book);
  arr[ch - 1] = Math.max(arr[ch - 1] || 0, Number(v));
}
const rows = [...counts.values()];
if (rows.length !== 66) throw new Error('expected 66 books');
const body = rows.map((r) => '  [' + r.join(',') + '],').join('\n');
writeFileSync(
  new URL('../src/core/versification.ts', import.meta.url),
  `// GENERATED by scripts/gen-versification.mjs — do not edit by hand.\n` +
    `// Verses per chapter for the 66 books, in canonical order (KJV numbering).\n` +
    `export const VERSE_COUNTS: number[][] = [\n${body}\n];\n`,
);
console.log('wrote versification for', rows.length, 'books,', rows.flat().reduce((a, b) => a + b, 0), 'verses');
